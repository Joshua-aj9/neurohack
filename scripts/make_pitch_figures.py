"""Collect the pitch figures from measured results only. Never fabricates: missing LIVE data is reported.

    uv run python scripts/make_pitch_figures.py

Sources (newest wins): results/g2_moabb*.json (PUBLIC DATASET), sessions/*ssvep_calibrate*/analysis.json
(G3 LIVE), sessions/*speller_*/results.json (G6 LIVE). Output: figures/pitch_*.png + figures/pitch_index.md
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

import numpy as np

from neurohack.config import REPO_ROOT
from neurohack.eval import figures

FIG, RES, SES = REPO_ROOT / "figures", REPO_ROOT / "results", REPO_ROOT / "sessions"


def newest(pattern: str, label: str | None = None) -> Path | None:
    hits = sorted(SES.glob(pattern), reverse=True)
    for h in hits:
        if label is None:
            return h
        res = h.parent / "results.json"
        if res.exists() and json.loads(res.read_text(encoding="utf-8")).get("label") == label:
            return h
    return None


def main() -> None:
    lines = ["# Pitch figures (generated by scripts/make_pitch_figures.py)", ""]
    # 1. accuracy vs window, public dataset
    g2 = RES / "g2_moabb.json"
    if g2.exists():
        d = json.loads(g2.read_text(encoding="utf-8"))
        L = d["curve_lengths"]
        p = figures.accuracy_vs_window(
            L,
            {"FBCCA": np.array(d["curve_fbcca_mean"]), "CCA": np.array(d["curve_cca_mean"])},
            d["chance"],
            f"PUBLIC DATASET Kalunga2016 ({'/'.join(d['channels'])})",
            FIG / "pitch_acc_vs_window_public.png",
        )
        lines.append(f"- `{p.name}` - PUBLIC DATASET, {d['n_subjects']} subjects")
        for src, dst in [
            ("g2_calibration.png", "pitch_calibration_public.png"),
            ("g2_confusion.png", "pitch_confusion_public.png"),
        ]:
            if (FIG / src).exists():
                shutil.copy2(FIG / src, FIG / dst)
                lines.append(f"- `{dst}` - PUBLIC DATASET (held-out)")
    # 2. live calibration session (G3)
    a = newest("*ssvep_calibrate*/analysis.json", "LIVE")
    if a:
        for name in ["acc_vs_window.png", "psd_oz.png", "confusion.png", "calibration.png"]:
            if (a.parent / name).exists():
                shutil.copy2(a.parent / name, FIG / f"pitch_live_{name}")
                el = json.loads(a.read_text(encoding="utf-8")).get("electrodes", "unknown")
                lines.append(f"- `pitch_live_{name}` - LIVE ({el} electrodes), {a.parent.name}")
    else:
        lines.append(
            "- LIVE accuracy / PSD / confusion / calibration: **missing** (run G3: apps/ssvep_calibrate.py)"
        )
    # 3. words/min LLM vs baseline (G6), LIVE only
    wpm: dict[str, list[float]] = {"baseline": [], "llm": []}
    conds: set[str] = set()
    for r in SES.glob("*speller_*/results.json"):
        d = json.loads(r.read_text(encoding="utf-8"))
        if d.get("label") != "LIVE":
            continue
        for s in d.get("sentences", []):
            wpm[s["mode"]].append(s["wpm"])
            conds.add(s.get("electrodes", d.get("electrodes", "unknown")))
    if wpm["baseline"] and wpm["llm"]:
        p = figures.bar_compare(
            ["letters only", "LLM suggestions"],
            [float(np.mean(wpm["baseline"])), float(np.mean(wpm["llm"]))],
            "words / min",
            f"LIVE ({'/'.join(sorted(conds))} electrodes): "
            f"n={len(wpm['baseline'])}/{len(wpm['llm'])} sentences",
            FIG / "pitch_wpm_live.png",
        )
        lines.append(
            f"- `{p.name}` - LIVE, mean words/min baseline {np.mean(wpm['baseline']):.2f} vs LLM "
            f"{np.mean(wpm['llm']):.2f}"
        )
    else:
        lines.append(
            "- words/min comparison: **missing** (needs LIVE speller sentences in both modes, G6)"
        )
    (FIG / "pitch_index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
